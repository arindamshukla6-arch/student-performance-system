"""
train_model.py
--------------
Builds the machine-learning part of the project end to end:

1. Generate a SYNTHETIC demonstration dataset  -> data/student_data.csv
2. Clean / preprocess it (missing values, encoding, scaling)
3. Split into training and testing sets
4. Train Logistic Regression, Decision Tree and Random Forest
5. Compare them using real evaluation results
6. Save the selected model with Joblib       -> models/student_model.pkl
7. Save the evaluation numbers               -> models/metrics.json

Run it with:  python train_model.py

IMPORTANT - about the data
--------------------------
No real student records are used. The dataset is generated by this script and
the risk label comes from a simple, documented scoring rule plus random noise.
The models therefore learn that synthetic rule. Their scores show that the
pipeline works; they say NOTHING about accuracy on real students.
"""

import json
import platform
from datetime import datetime
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
import sklearn
from sklearn.ensemble import RandomForestClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (
    accuracy_score,
    classification_report,
    confusion_matrix,
    f1_score,
    precision_score,
    recall_score,
)
from sklearn.model_selection import StratifiedKFold, cross_val_score, train_test_split
from sklearn.pipeline import Pipeline
from sklearn.tree import DecisionTreeClassifier

from preprocessing import (
    ASSIGNMENT_OPTIONS,
    CATEGORICAL_FEATURES,
    FEATURES,
    NUMERIC_FEATURES,
    RISK_LABELS,
    TARGET,
    build_preprocessor,
)

BASE_DIR = Path(__file__).resolve().parent
DATA_PATH = BASE_DIR / "data" / "student_data.csv"
DEMO_STUDENTS_PATH = BASE_DIR / "data" / "demo_students.csv"
MODEL_PATH = BASE_DIR / "models" / "student_model.pkl"
METRICS_PATH = BASE_DIR / "models" / "metrics.json"

RANDOM_STATE = 42
N_ROWS = 1500
TEST_SIZE = 0.2
MISSING_RATE = 0.03  # share of values blanked out to demonstrate imputation

# Synthetic labelling rule (documented so it can be explained in a viva):
#   score = 0.30*attendance + 0.30*internal% + 0.25*previous% + 0.15*assignment points
#   assignment points: Completed=100, Partially Completed=50, Not Completed=0
#   score >= 70  -> Low Risk, 58 <= score < 70 -> Moderate Risk, score < 58 -> High Risk
#   (random noise is added to the score so the task is not perfectly predictable)
ASSIGNMENT_POINTS = {"Completed": 100, "Partially Completed": 50, "Not Completed": 0}
LOW_CUTOFF = 70
MODERATE_CUTOFF = 58


# ---------------------------------------------------------------------------
# 1. Synthetic data
# ---------------------------------------------------------------------------
def generate_students(n, seed):
    """Create n synthetic students with complete values (no missing data)."""
    rng = np.random.default_rng(seed)

    previous = np.clip(rng.normal(64, 16, n), 20, 100)
    attendance = np.clip(0.35 * (previous - 64) + rng.normal(76, 15, n), 25, 100)
    internal = np.clip(0.6 * (previous - 64) + rng.normal(62, 14, n), 5, 100)

    # Students with low attendance are more likely to leave assignments pending.
    p_completed = np.clip((attendance - 30) / 85, 0.05, 0.9)
    p_not = np.clip((75 - attendance) / 90, 0.03, 0.6)
    status = []
    for pc, pn in zip(p_completed, p_not):
        p_part = max(1 - pc - pn, 0.05)
        probs = np.array([pc, p_part, pn])
        status.append(rng.choice(ASSIGNMENT_OPTIONS, p=probs / probs.sum()))

    points = np.array([ASSIGNMENT_POINTS[s] for s in status])
    score = (
        0.30 * attendance + 0.30 * internal + 0.25 * previous + 0.15 * points
        + rng.normal(0, 3.5, n)
    )
    risk = np.where(score >= LOW_CUTOFF, "Low Risk",
                    np.where(score >= MODERATE_CUTOFF, "Moderate Risk", "High Risk"))

    return pd.DataFrame(
        {
            "attendance": attendance.round(1),
            "internal_marks_pct": internal.round(1),
            "assignment_status": status,
            "previous_performance_pct": previous.round(1),
            TARGET: risk,
        }
    )


def add_missing_values(df, rate, seed):
    """Blank out a small share of feature values to mimic real, messy data."""
    rng = np.random.default_rng(seed)
    df = df.copy()
    for column in FEATURES:
        mask = rng.random(len(df)) < rate
        df[column] = df[column].astype(object).where(~mask, np.nan)
    for column in NUMERIC_FEATURES:
        df[column] = pd.to_numeric(df[column])
    return df


def build_demo_students(n=60, seed=7):
    """Create the sample records shown in the web app (fake IDs and names)."""
    df = generate_students(n, seed)
    rng = np.random.default_rng(seed)
    max_marks = rng.choice([20, 25, 30, 50], size=n)
    out = pd.DataFrame(
        {
            "student_id": [f"DEMO{i:03d}" for i in range(1, n + 1)],
            "name": [f"Demo Student {i:02d}" for i in range(1, n + 1)],
            "attendance": df["attendance"],
            "internal_max": max_marks,
            "internal_obtained": (df["internal_marks_pct"] / 100 * max_marks).round(1),
            "assignment_status": df["assignment_status"],
            "previous_performance_pct": df["previous_performance_pct"],
        }
    )
    return out


# ---------------------------------------------------------------------------
# 2-5. Training and comparison
# ---------------------------------------------------------------------------
def make_models():
    """The three algorithms required by the project."""
    return {
        "Logistic Regression": LogisticRegression(max_iter=1000, random_state=RANDOM_STATE),
        "Decision Tree": DecisionTreeClassifier(max_depth=5, random_state=RANDOM_STATE),
        "Random Forest": RandomForestClassifier(
            n_estimators=200, max_depth=8, random_state=RANDOM_STATE
        ),
    }


def feature_importance(pipeline):
    """Return {feature: importance} for the fitted pipeline (sums to 1)."""
    pre = pipeline.named_steps["preprocess"]
    model = pipeline.named_steps["model"]
    names = [n.split("__", 1)[1] for n in pre.get_feature_names_out()]
    if hasattr(model, "feature_importances_"):
        values = np.asarray(model.feature_importances_, dtype=float)
    else:  # Logistic Regression: average absolute coefficient across classes
        values = np.abs(model.coef_).mean(axis=0)
    values = values / values.sum()
    return {name: round(float(v), 4) for name, v in zip(names, values)}


def main():
    print("=" * 60)
    print("AI-Based Student Performance Prediction - model training")
    print("=" * 60)

    # --- 1. data -----------------------------------------------------------
    DATA_PATH.parent.mkdir(exist_ok=True)
    MODEL_PATH.parent.mkdir(exist_ok=True)

    complete = generate_students(N_ROWS, RANDOM_STATE)
    data = add_missing_values(complete, MISSING_RATE, RANDOM_STATE + 1)
    data.to_csv(DATA_PATH, index=False)
    build_demo_students().to_csv(DEMO_STUDENTS_PATH, index=False)
    print(f"Saved SYNTHETIC dataset ({len(data)} rows) -> {DATA_PATH.name}")

    # --- 2. cleaning ---------------------------------------------------------
    df = pd.read_csv(DATA_PATH)
    df = df.drop_duplicates()
    df = df.dropna(subset=[TARGET])  # a row without a label cannot be used
    df = df[df[TARGET].isin(RISK_LABELS)]
    # Out-of-range numbers become "missing" so the imputer can handle them.
    for column in NUMERIC_FEATURES:
        df.loc[(df[column] < 0) | (df[column] > 100), column] = np.nan
    missing_before = int(df[FEATURES].isna().sum().sum())
    print(f"Missing feature values to be imputed inside the pipeline: {missing_before}")
    print("Class counts:", df[TARGET].value_counts().to_dict())

    # --- 3. split ------------------------------------------------------------
    X = df[FEATURES]
    y = df[TARGET]
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=TEST_SIZE, random_state=RANDOM_STATE, stratify=y
    )
    print(f"Training rows: {len(X_train)}   Testing rows: {len(X_test)}")

    # --- 4 & 5. train + compare ------------------------------------------
    cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=RANDOM_STATE)
    results = {}
    fitted = {}
    for name, estimator in make_models().items():
        pipeline = Pipeline([("preprocess", build_preprocessor()), ("model", estimator)])

        # Cross-validation uses ONLY the training data -> used to pick the model,
        # so the test set stays untouched until the final report.
        cv_scores = cross_val_score(pipeline, X_train, y_train, cv=cv, scoring="f1_macro")

        pipeline.fit(X_train, y_train)
        predicted = pipeline.predict(X_test)
        matrix = confusion_matrix(y_test, predicted, labels=RISK_LABELS)

        results[name] = {
            "cv_f1_macro_mean": round(float(cv_scores.mean()), 4),
            "cv_f1_macro_std": round(float(cv_scores.std()), 4),
            "accuracy": round(float(accuracy_score(y_test, predicted)), 4),
            "precision_macro": round(float(precision_score(y_test, predicted, average="macro", zero_division=0)), 4),
            "recall_macro": round(float(recall_score(y_test, predicted, average="macro", zero_division=0)), 4),
            "f1_macro": round(float(f1_score(y_test, predicted, average="macro", zero_division=0)), 4),
            "confusion_matrix": matrix.tolist(),
            "classification_report": classification_report(
                y_test, predicted, labels=RISK_LABELS, output_dict=True, zero_division=0
            ),
        }
        fitted[name] = pipeline
        print(
            f"{name:<20} CV F1 {cv_scores.mean():.3f}  |  test accuracy "
            f"{results[name]['accuracy']:.3f}  F1 {results[name]['f1_macro']:.3f}"
        )

    # Select by cross-validated macro F1 (macro F1 treats all three risk
    # levels equally, so a model cannot win by ignoring the smaller class).
    selected = max(results, key=lambda n: results[n]["cv_f1_macro_mean"])
    print(f"\nSelected model: {selected}")

    # --- 6. save -----------------------------------------------------------
    joblib.dump(fitted[selected], MODEL_PATH)
    print(f"Saved model -> {MODEL_PATH}")

    metrics = {
        "trained_at": datetime.now().strftime("%Y-%m-%d %H:%M"),
        "selected_model": selected,
        "selection_rule": "Highest mean 5-fold cross-validated macro F1 on the training data.",
        "labels": RISK_LABELS,
        "dataset": {
            "type": "SYNTHETIC demonstration data (not real student records)",
            "rows_used": int(len(df)),
            "train_rows": int(len(X_train)),
            "test_rows": int(len(X_test)),
            "missing_values_imputed": missing_before,
            "class_counts": {k: int(v) for k, v in df[TARGET].value_counts().items()},
            "labelling_rule": (
                "score = 0.30*attendance + 0.30*internal% + 0.25*previous% + "
                "0.15*assignment points (+ random noise); "
                f"score >= {LOW_CUTOFF} Low, >= {MODERATE_CUTOFF} Moderate, otherwise High."
            ),
        },
        "models": results,
        "feature_importance": feature_importance(fitted[selected]),
        "environment": {
            "scikit_learn": sklearn.__version__,
            "python": platform.python_version(),
        },
    }
    METRICS_PATH.write_text(json.dumps(metrics, indent=2))
    print(f"Saved evaluation results -> {METRICS_PATH}")
    print("\nDone. Next step: python app.py")


if __name__ == "__main__":
    main()
